"""Count reference classes of newly added positive pseudo-labels.

Local additions are reconstructed from saved pixel-wise predictions. Transfer
additions can be read from an archived index file or reconstructed with
6_Transfer_Iterative_RF_Core.py and 6_Transfer_Initial_RF.py.

Use saved_indices to audit the historical table without retraining its models.
Use replay_core only for outputs generated by the configured English transfer
scripts. The two workflows must not be assumed to produce identical additions.
Replace the descriptive path placeholders before running.
"""

from pathlib import Path
import csv
import gc
import importlib.util
import json
import sys

import numpy as np
import rasterio
from rasterio.warp import reproject, Resampling


OUT = Path("<PATH_TO_PSEUDO_LABEL_REFERENCE_CLASS_OUTPUT_DIRECTORY>")
TRANSFER_MODE = "saved_indices"  # Either saved_indices or replay_core.
TRANSFER_INDEX_ARCHIVE = Path("<PATH_TO_SAVED_NEW_POSITIVE_PIXEL_INDICES_NPZ>")
TRANSFER_CORE_PATH = (
    Path("<PATH_TO_DIRECTORY_CONTAINING_TRANSFER_SCRIPTS>")
    / "6_Transfer_Iterative_RF_Core.py"
)

# Archive keys identify HDF5 row indices, not raster row or column indices.
TRANSFER_ARCHIVE_KEYS = {"site2": "transfer_haiyan", "site3": "transfer_yuhang"}
STRATEGIES = {"site1": "ADC", "site2": "CEE", "site3": "BCE"}
SITE_LABELS = {"site1": "Site 1", "site2": "Site 2", "site3": "Site 3"}
COUNT_FIELDS = ("Added", "Rapeseed-rice", "Wheat-rice", "Double rice", "Other/unassigned")

# Prediction maps must be pixel-wise maps from before parcel-level voting.
# Each map in iteration_maps corresponds to the indicated strategy prefix.
SITE_CONFIGS = {
    key: {
        "field_raster": f"<PATH_TO_{key.upper()}_UNLABELLED_PARCEL_ID_TIFF>",
        "pixel_mapping": f"<PATH_TO_{key.upper()}_RASTER_TO_HDF5_INDEX_NPY>",
        "initial_map": f"<PATH_TO_{key.upper()}_INITIAL_RF_PIXELWISE_TIFF>",
        "initial_positive_map": f"<PATH_TO_{key.upper()}_INITIAL_POSITIVE_SEED_TIFF>",
        "iteration_maps": {
            strategy[:i]: f"<PATH_TO_{key.upper()}_{strategy[:i]}_PIXELWISE_TIFF>"
            for i in (1, 2)
        },
    }
    for key, strategy in STRATEGIES.items()
}
LABEL_RASTERS = {
    key: {
        "Rapeseed-rice": f"<PATH_TO_{key.upper()}_RAPESEED_RICE_REFERENCE_TIFF>",
        "Wheat-rice": f"<PATH_TO_{key.upper()}_WHEAT_RICE_REFERENCE_TIFF>",
        "Double rice": (
            None if key == "site2"
            else f"<PATH_TO_{key.upper()}_DOUBLE_RICE_REFERENCE_TIFF>"
        ),
    }
    for key in STRATEGIES
}

AUDIT = {"selection_sources": [], "reference_overlap_checks": []}
DETAIL, TRANSFER_DETAIL, SUMMARY = [], [], []
PIXELS = {}


def configured_path(value):
    path = Path(value)
    if "<PATH_TO_" in str(path):
        raise ValueError(f"Replace the descriptive path placeholder: {path}")
    if not path.is_file():
        raise FileNotFoundError(path)
    return path


def read_raster(path, reference=None):
    with rasterio.open(configured_path(path)) as src:
        if reference is not None and (
            src.shape != (reference["height"], reference["width"])
            or src.transform != reference["transform"]
            or src.crs != reference["crs"]
        ):
            raise ValueError(f"Raster grid does not match the parcel grid: {path}")
        return src.read(1), src.profile, src.read_masks(1).astype(bool)


def read_grid(cfg):
    field, meta, mask = read_raster(cfg["field_raster"])
    mapping = np.load(configured_path(cfg["pixel_mapping"]), mmap_mode="r")
    if mapping.shape != field.shape or not np.issubdtype(mapping.dtype, np.integer):
        raise ValueError("The integer raster-to-HDF5 mapping must match the parcel raster dimensions.")
    valid = (field > 0) & mask & (mapping >= 0)
    if not valid.any():
        raise ValueError("No parcel pixels have valid HDF5 indices.")
    return field, meta, mapping, valid


def read_reference_classes(key, meta):
    masks = []
    for label in COUNT_FIELDS[1:4]:
        path = LABEL_RASTERS[key][label]
        destination = np.zeros((meta["height"], meta["width"]), dtype=np.uint8)
        if path is not None:
            with rasterio.open(configured_path(path)) as src:
                source = ((src.read(1) > 0) & src.read_masks(1).astype(bool)).astype(np.uint8)
                reproject(
                    source, destination, src_transform=src.transform, src_crs=src.crs,
                    dst_transform=meta["transform"], dst_crs=meta["crs"],
                    src_nodata=0, dst_nodata=0, resampling=Resampling.nearest,
                )
        masks.append(destination.ravel().astype(bool))
    return masks


def classify(indices, masks):
    indices = np.asarray(indices, dtype=np.int64)
    if len(np.unique(indices)) != len(indices):
        raise ValueError("New positive sample indices must not contain duplicates.")
    if len(indices) and (indices.min() < 0 or indices.max() >= len(masks[0])):
        raise ValueError("Sample indices are outside the reference grid.")
    target, wheat, double = np.vstack([mask[indices] for mask in masks])
    conflict = ~target & wheat & double
    if conflict.any():
        raise ValueError(f"Conflicting wheat-rice and double-rice labels cover {int(conflict.sum())} pixels.")
    AUDIT["reference_overlap_checks"].append({
        "selected_pixel_count": len(indices),
        "target_also_wheat": int((target & wheat).sum()),
        "target_also_double": int((target & double).sum()),
        "wrong_positive_wheat_double_conflicts": int(conflict.sum()),
    })
    # Resolve target-reference membership before classifying wrong positives.
    counts = [int(target.sum()), int((~target & wheat).sum()), int((~target & double).sum())]
    return dict(zip(COUNT_FIELDS, [len(indices), *counts, len(indices) - sum(counts)]))


def numeric_prefix(prefix):
    if not prefix or any(letter not in "ABCDE" for letter in prefix):
        raise ValueError(f"Invalid interval sequence: {prefix}")
    return "".join(str(ord(letter) - ord("A") + 1) for letter in prefix)


def selected_local_parcels(field, prediction, valid, letter):
    # Reproduce the historical local interval boundaries; 0% parcels are excluded.
    ids, inverse, totals = np.unique(field[valid], return_inverse=True, return_counts=True)
    positives = np.bincount(inverse, weights=(prediction[valid] == 1), minlength=len(ids))
    ratios = positives / totals
    interval = int(numeric_prefix(letter))
    lower = (interval - 1) / 5
    upper = interval / 5
    if interval == 1:
        chosen = (ratios > 0) & (ratios < upper)
    elif interval == 5:
        chosen = (ratios >= lower) & (ratios <= upper)
    else:
        chosen = (ratios >= lower) & (ratios < upper)
    return ids[chosen]


def local_paths():
    for key, strategy in STRATEGIES.items():
        cfg = SITE_CONFIGS[key]
        field, meta, mapping, valid = read_grid(cfg)
        prediction, _, _ = read_raster(cfg["initial_map"], meta)
        seeds, _, seed_mask = read_raster(cfg["initial_positive_map"], meta)
        seed_indices = np.flatnonzero((seeds == 1) & seed_mask & valid)
        masks = read_reference_classes(key, meta)
        cumulative = np.array([], dtype=np.int64)
        for iteration, letter in enumerate(strategy, 1):
            # Historical maps declare 0 as NoData, but 0 represents non-target
            # inside parcels with valid HDF5 indices. Preserve that convention.
            if not np.isin(prediction[valid], (0, 1)).all():
                raise ValueError(f"Missing or non-binary pixel-wise predictions within valid parcels: {key}")
            selected = selected_local_parcels(field, prediction, valid, letter)
            candidates = np.flatnonzero(valid & np.isin(field, selected) & (prediction == 0))
            new = np.setdiff1d(candidates, np.union1d(cumulative, seed_indices), assume_unique=True)
            counts = classify(new, masks)
            prefix = strategy[:iteration]
            DETAIL.append({"Experiment": SITE_LABELS[key], "Strategy": strategy,
                           "Iteration": iteration, "Prefix": prefix, **counts})
            PIXELS[f"{key}_{prefix}_flat_raster_indices"] = new
            cumulative = np.union1d(cumulative, new)
            source = cfg["initial_map"] if iteration == 1 else cfg["iteration_maps"][strategy[:iteration - 1]]
            AUDIT["selection_sources"].append({"experiment": SITE_LABELS[key],
                "iteration": iteration, "map": str(source), "field_raster": str(cfg["field_raster"])})
            print(DETAIL[-1], flush=True)
            if iteration < 3:
                prediction, _, _ = read_raster(cfg["iteration_maps"][prefix], meta)
        SUMMARY.append({"Experiment": SITE_LABELS[key], "Strategy": strategy, **classify(cumulative, masks)})
        del field, mapping, valid, prediction, seeds, masks
        gc.collect()


def record_transfer_source(key, iteration, new, masks):
    prefix = "DCE"[:iteration]
    counts = classify(new, masks)
    TRANSFER_DETAIL.append({"Experiment": "Site 1*", "Source": SITE_LABELS[key],
                           "Strategy": "DCE", "Iteration": iteration, "Prefix": prefix, **counts})
    PIXELS[f"transfer_{key}_{prefix}_flat_raster_indices"] = new
    return counts


def finish_transfer():
    for iteration in (1, 2, 3):
        parts = [row for row in TRANSFER_DETAIL if row["Iteration"] == iteration]
        if len(parts) != 2:
            raise ValueError("Each transfer iteration must include both source regions.")
        counts = {field: sum(row[field] for row in parts) for field in COUNT_FIELDS}
        row = {"Experiment": "Site 1*", "Strategy": "DCE", "Iteration": iteration,
               "Prefix": "DCE"[:iteration], **counts}
        DETAIL.append(row)
        print(row, flush=True)
    SUMMARY.append({"Experiment": "Site 1*", "Strategy": "DCE",
                    **{field: sum(row[field] for row in TRANSFER_DETAIL) for field in COUNT_FIELDS}})


def transfer_from_saved_indices():
    with np.load(configured_path(TRANSFER_INDEX_ARCHIVE), allow_pickle=False) as archive:
        for key in ("site2", "site3"):
            field, meta, mapping, valid = read_grid(SITE_CONFIGS[key])
            masks = read_reference_classes(key, meta)
            flat = np.flatnonzero(valid)
            h5_indices = np.asarray(mapping.ravel()[flat], dtype=np.int64)
            order = np.argsort(h5_indices)
            h5_indices, flat = h5_indices[order], flat[order]
            if len(np.unique(h5_indices)) != len(h5_indices):
                raise ValueError("The archived-index workflow requires one raster pixel per HDF5 index.")
            previous = np.array([], dtype=np.int64)
            for iteration in (1, 2, 3):
                prefix = numeric_prefix("DCE"[:iteration])
                name = f"{TRANSFER_ARCHIVE_KEYS[key]}_{prefix}_hdf5_indices"
                new_h5 = np.asarray(archive[name], dtype=np.int64)
                if new_h5.ndim != 1 or len(np.unique(new_h5)) != len(new_h5):
                    raise ValueError(f"Archived additions must be unique one-dimensional indices: {name}")
                positions = np.searchsorted(h5_indices, new_h5)
                if np.any(positions >= len(h5_indices)) or not np.array_equal(h5_indices[positions], new_h5):
                    raise ValueError(f"Archived indices do not match the configured source mapping: {name}")
                new = flat[positions]
                if np.intersect1d(previous, new).size:
                    raise ValueError("Archived additions overlap between iterations.")
                previous = np.union1d(previous, new)
                # Retain the HDF5-index keys so the output archive can be read again.
                PIXELS[name] = new_h5.copy()
                record_transfer_source(key, iteration, new, masks)
            del field, mapping, valid, masks
            gc.collect()
    AUDIT["transfer_replay"] = {"mode": "saved_indices", "source_only": True,
        "index_archive": str(TRANSFER_INDEX_ARCHIVE), "models_rebuilt": []}
    finish_transfer()


def load_transfer_core():
    path = configured_path(TRANSFER_CORE_PATH).resolve()
    directory = str(path.parent)
    if directory not in sys.path:
        sys.path.insert(0, directory)
    spec = importlib.util.spec_from_file_location("pseudo_label_transfer_core", path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Cannot load the transfer core: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    for name in ("base", "interval_parcels", "fit_model", "build_features"):
        if not hasattr(module, name):
            raise AttributeError(f"The English transfer core is missing {name}: {path}")
    return module


def transfer_from_core():
    itr = load_transfer_core()
    base = itr.base
    keys = tuple(base.SOURCE_KEYS)
    if set(keys) != {"site2", "site3"}:
        raise ValueError("The transfer source regions must be site2 and site3.")
    sites = {key: base.load_site(key) for key in keys}
    seeds, raw, masks, cumulative, previous = {}, {}, {}, {}, {}
    for key, site in sites.items():
        path = configured_path(base.cache_directory() / f"{key}_initial_state.npz")
        with np.load(path, allow_pickle=False) as cache:
            if not np.array_equal(cache["field_indices"], site.field_indices):
                raise ValueError(f"Initial transfer cache and field mapping differ: {key}")
            seeds[key] = np.unique(cache["positive_seeds"].astype(np.int64))
            raw[key] = cache["predictions"].copy()
        meta = dict(height=site.rows, width=site.cols, transform=site.transform, crs=site.crs)
        masks[key] = read_reference_classes(key, meta)
        cumulative[key] = np.array([], dtype=np.int64)
        previous[key] = np.array([], dtype=np.int64)
    for iteration, letter in enumerate("DCE", 1):
        positives, negatives = {}, {}
        for key, site in sites.items():
            if raw[key].shape != site.field_indices.shape or not np.isin(raw[key], (0, 1)).all():
                raise ValueError(f"Invalid source-region prediction vector: {key}")
            selected, zero = itr.interval_parcels(raw[key], site.parcel_ids, int(numeric_prefix(letter)))
            candidates = site.field_indices[np.isin(site.parcel_ids, selected) & (raw[key] == 0)]
            new = np.setdiff1d(candidates, np.union1d(seeds[key], cumulative[key]))
            rows, columns = site.inverse_row[new], site.inverse_col[new]
            if np.any(rows < 0) or np.any(columns < 0):
                raise ValueError(f"A new source sample has no raster position: {key}")
            flat = np.ravel_multi_index((rows, columns), (site.rows, site.cols))
            if np.intersect1d(previous[key], flat).size:
                raise ValueError("Reconstructed transfer additions overlap between iterations.")
            previous[key] = np.union1d(previous[key], flat)
            archive_key = f"{TRANSFER_ARCHIVE_KEYS[key]}_{numeric_prefix('DCE'[:iteration])}_hdf5_indices"
            PIXELS[archive_key] = new.copy()
            record_transfer_source(key, iteration, flat, masks[key])
            cumulative[key] = np.union1d(cumulative[key], candidates)
            positives[key] = np.union1d(seeds[key], cumulative[key])
            negatives[key] = site.field_indices[np.isin(site.parcel_ids, zero)]
        if iteration < 3:
            model = itr.fit_model(sites, positives, negatives)
            raw = {key: base.predict_site(model, sites[key], itr.build_features) for key in keys}
            del model
            gc.collect()
    AUDIT["transfer_replay"] = {"mode": "replay_core", "source_only": True,
        "transfer_core": str(TRANSFER_CORE_PATH), "models_rebuilt": ["D", "DC"],
        "negative_sampling": "Reconstructed from zero-proportion source parcels at each iteration"}
    finish_transfer()


def write_outputs():
    if "<PATH_TO_" in str(OUT):
        raise ValueError("Replace the output-directory placeholder before running.")
    OUT.mkdir(parents=True, exist_ok=True)
    for filename, rows in (("by_iteration.csv", DETAIL), ("three_iteration_totals.csv", SUMMARY),
                           ("transfer_by_source.csv", TRANSFER_DETAIL)):
        with (OUT / filename).open("w", encoding="utf-8-sig", newline="") as handle:
            writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
            writer.writeheader()
            writer.writerows(rows)
    np.savez_compressed(OUT / "reconstructed_new_positive_pixel_indices.npz", **PIXELS)
    AUDIT["reference_rasters"] = LABEL_RASTERS
    AUDIT["local_interval_boundaries"] = "(0, 0.2), [0.2, 0.4), [0.4, 0.6), [0.6, 0.8), [0.8, 1]"
    AUDIT["reference_policy"] = "Target-reference priority; other/unassigned is outside all three crop masks"
    (OUT / "source_and_validation_audit.json").write_text(json.dumps(AUDIT, indent=2), encoding="utf-8")
    lines = ["# Reference classes of newly added positive pseudo-labels", "",
             "Counts exclude initial seeds and additions from earlier iterations. Target-reference membership takes priority when crop masks overlap. Other/unassigned is not an independently verified crop class. Transfer samples come from source Sites 2 and 3 only.",
             "", f"Transfer reconstruction mode: {TRANSFER_MODE}.", ""]
    for title, rows in (("Three-iteration totals", SUMMARY), ("By iteration", DETAIL),
                        ("Transfer by source", TRANSFER_DETAIL)):
        fields = list(rows[0])
        lines.extend(["## " + title, "", "| " + " | ".join(fields) + " |", "|" + "---|" * len(fields)])
        lines.extend("| " + " | ".join(str(row[field]) for field in fields) + " |" for row in rows)
        lines.append("")
    (OUT / "selected_strategy_reference_classes.md").write_text("\n".join(lines), encoding="utf-8")


def main():
    if "<PATH_TO_" in str(OUT):
        raise ValueError("Replace the descriptive output-directory placeholder before running.")
    if TRANSFER_MODE not in ("saved_indices", "replay_core"):
        raise ValueError("TRANSFER_MODE must be saved_indices or replay_core.")
    local_paths()
    if TRANSFER_MODE == "saved_indices":
        transfer_from_saved_indices()
    else:
        transfer_from_core()
    for summary in SUMMARY:
        rows = [row for row in DETAIL if row["Experiment"] == summary["Experiment"]]
        for field in COUNT_FIELDS:
            if sum(row[field] for row in rows) != summary[field]:
                raise ValueError(f"Iteration totals do not match the cumulative counts: {summary['Experiment']}")
    write_outputs()
    print("Completed reference-class counts:", SUMMARY, flush=True)


if __name__ == "__main__":
    main()
